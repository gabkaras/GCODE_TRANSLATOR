"""Write layer paths as G-code (Marlin/RepRap flavour, absolute XYZ, absolute E).

Handles per-segment speeds (overhang slow-down), per-path flow (bridges, combined
infill), first-layer flow, a volumetric speed cap, minimum layer time, retraction
with wipe / coast / extra prime, Z hop, spiral-vase Z ramps and the tool axis
(I J K) of non-planar layers.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from .params import SliceParams, bead_area
from .toolpath import Layer, Path


@dataclass
class SliceStats:
    layers: int = 0
    paths: int = 0
    extrusion_length: float = 0.0  # mm of path with extrusion
    travel_length: float = 0.0
    e_total: float = 0.0  # E units (mm^3 or mm filament)
    volume_mm3: float = 0.0  # deposited material regardless of the E mode
    mass_g: float = 0.0
    time_s: float = 0.0
    dropped_chains: int = 0
    bounds: dict = field(default_factory=dict)
    by_type: dict = field(default_factory=dict)  # mm per feature kind
    by_type_time: dict = field(default_factory=dict)  # s per feature kind
    layer_mode: str = "planar"
    support_area: float = 0.0  # overhang indicator (mm^2 over all layers)
    support_layers: int = 0
    support_volume: float = 0.0  # generated support (mm^3)
    bridges: int = 0
    overhang_length: float = 0.0  # mm of wall printed slower because it hangs over air
    slowed_layers: int = 0  # layers slowed down by the minimum layer time
    min_layer_height: float = 0.0
    max_layer_height: float = 0.0
    max_tilt: float = 0.0  # largest tool tilt from vertical (deg)


def _seg_speeds(path: Path, feed: float) -> np.ndarray:
    n = len(path.points)
    if path.speeds is not None and len(path.speeds) == n:
        return np.minimum(path.speeds, feed) if feed < path.speed else path.speeds
    return np.full(n, feed)


def write_gcode(layers: list[Layer], params: SliceParams, source: str = "") -> tuple[str, SliceStats]:
    p = params
    st = SliceStats(layers=len(layers))
    out: list[str] = []
    f = lambda v: f"{v:.3f}"  # noqa: E731
    out.append("; generated by gcode2krl slicer" + (f" from {source}" if source else ""))
    out.append(f"; layer_height={p.layer_height} bead_width={p.bead_width} perimeters={p.perimeters} infill={p.infill_density} ({p.infill_pattern})"
               + (" adaptive" if p.adaptive_layers else "") + (f" support={p.support}" if p.support != "none" else "")
               + (" spiral_vase" if p.spiral_vase else ""))
    out.append(f";LAYER_COUNT:{len(layers)}")
    out.append("G21 ; mm")
    out.append("G90 ; absolute")
    out.append("M82 ; absolute E")
    out.append("G92 E0")
    if p.start_gcode.strip():
        out.extend(p.start_gcode.splitlines())
    e = 0.0
    cur = None  # current XYZ
    retracted = False
    all_pts = []
    st.layer_mode = p.layer_mode
    heights = [L.height for L in layers if L.paths]
    if heights:
        st.min_layer_height, st.max_layer_height = float(min(heights)), float(max(heights))
    density = p.material_density  # g/cm^3

    def travel_feed() -> float:
        return p.speed_travel

    for L in layers:
        if not L.paths:
            continue
        z = L.z + p.z_offset
        if p.comments:
            out.append(f";LAYER:{L.index}")
            out.append(f";Z:{z:.3f}")
            out.append(f";HEIGHT:{L.height:.3f}")
        first_model = L.kind == "model" and L.index == next((x.index for x in layers if x.kind == "model"), -1)
        flow_layer = p.first_layer_flow if first_model else 1.0
        # ---- nominal layer time (for the minimum layer time rule)
        feeds = []
        for path in L.paths:
            feed = path.speed
            if p.max_volumetric_speed > 0:
                area = bead_area(path.width, L.height) * path.flow * flow_layer
                cap = p.max_volumetric_speed / max(area, 1e-9) * 60.0  # mm/min
                feed = min(feed, cap)
            feeds.append(feed)
        t_nom = 0.0
        for path, feed in zip(L.paths, feeds):
            P = path.xyz if path.xyz is not None else path.points
            if len(P) < 2:
                continue
            seg = np.linalg.norm(np.diff(P, axis=0), axis=1)
            sp = _seg_speeds(path, feed)[1:len(P)]
            t_nom += float((seg / np.maximum(sp / 60.0, 1e-6)).sum())
            if path.closed:
                t_nom += float(np.linalg.norm(P[0] - P[-1]) / max(sp[0] / 60.0, 1e-6))
        scale = 1.0
        if p.min_layer_time > 0 and 0 < t_nom < p.min_layer_time:
            scale = t_nom / p.min_layer_time
            st.slowed_layers += 1
        if retracted is False and p.retract_layer_change and p.retract_length > 0 and cur is not None:
            e -= p.retract_length
            out.append(f"G1 E{e:.5f} F{p.retract_speed:.0f}")
            retracted = True
        for path, feed in zip(L.paths, feeds):
            pts = path.points
            if len(pts) < 2:
                continue
            st.paths += 1
            if path.kind == "BRIDGE":
                st.bridges += 1
            if p.comments:
                out.append(f";TYPE:{path.kind}")
            planar = path.xyz is None
            P3 = path.xyz if not planar else np.column_stack([pts, np.full(len(pts), z)])
            if not planar:
                P3 = P3 + np.array([0.0, 0.0, p.z_offset])
            axes = path.axes if (not planar and p.tool_axis and path.axes is not None) else None
            tf = path.tf if path.tf is not None else np.ones(len(P3))
            e_per_mm = p.extrusion_per_mm(path.width, L.height) * path.flow * flow_layer
            vol_per_mm = bead_area(path.width, L.height) * path.flow * flow_layer
            speeds = _seg_speeds(path, feed)
            if scale < 1.0:
                speeds = np.maximum(speeds * scale, min(p.min_speed, feed))
            start = P3[0]
            # ---- travel to the start
            dist = float(np.linalg.norm(start - cur)) if cur is not None else 0.0
            if cur is None or dist > 1e-3:
                if p.retract_length > 0 and dist >= p.min_travel_for_retract and not retracted:
                    e -= p.retract_length
                    out.append(f"G1 E{e:.5f} F{p.retract_speed:.0f}")
                    retracted = True
                hop = p.z_hop if (p.z_hop > 0 and dist >= p.min_travel_for_retract) else 0.0
                zt = float(start[2])
                ax = f" I{axes[0][0]:.4f} J{axes[0][1]:.4f} K{axes[0][2]:.4f}" if axes is not None else ""
                if hop > 0:
                    out.append(f"G0 Z{f(max(zt, (cur[2] if cur is not None else zt)) + hop)} F{travel_feed():.0f}")
                    out.append(f"G0 X{f(start[0])} Y{f(start[1])}{ax} F{travel_feed():.0f}")
                    out.append(f"G0 Z{f(zt)} F{travel_feed():.0f}")
                elif planar and cur is not None and abs(zt - cur[2]) > 1e-6 and abs(start[0] - cur[0]) < 1e-6 and abs(start[1] - cur[1]) < 1e-6:
                    out.append(f"G0 Z{f(zt)} F{travel_feed():.0f}")
                else:
                    if planar and (cur is None or abs(zt - cur[2]) > 1e-6):
                        out.append(f"G0 Z{f(zt)} F{travel_feed():.0f}")
                    out.append(f"G0 X{f(start[0])} Y{f(start[1])}{'' if planar else ' Z' + f(zt)}{ax} F{travel_feed():.0f}")
                st.travel_length += dist
                st.time_s += dist / (travel_feed() / 60.0)
                if retracted:
                    e += p.retract_length + p.retract_extra_prime
                    out.append(f"G1 E{e:.5f} F{p.retract_speed:.0f}")
                    retracted = False
            # ---- extrude along the path
            idx = list(range(1, len(P3))) + ([0] if path.closed else [])
            total_len = float(np.linalg.norm(np.diff(np.vstack([P3, P3[:1]]) if path.closed else P3, axis=0), axis=1).sum())
            coast = p.coast_length if (path.closed and path.kind in ("WALL-OUTER", "WALL-INNER") and p.coast_length > 0 and total_len > 3 * p.coast_length) else 0.0
            cur_feed = None
            prev_i = 0
            done = 0.0
            for i in idx:
                q = P3[i]
                d = float(np.linalg.norm(q - P3[prev_i]))
                if d < 1e-6:
                    prev_i = i
                    continue
                feed_i = float(speeds[i] if i < len(speeds) else speeds[0])
                if cur_feed is None or abs(feed_i - cur_feed) >= 1.0:
                    out.append(f"G1 F{feed_i:.0f}")
                    cur_feed = feed_i
                ax = f" I{axes[i][0]:.4f} J{axes[i][1]:.4f} K{axes[i][2]:.4f}" if axes is not None else ""
                zs = "" if planar else f" Z{f(q[2])}"
                thick = float((tf[i] + tf[prev_i]) / 2.0)
                remaining_after = total_len - (done + d)
                if coast > 0 and remaining_after < coast:
                    # split: extrude up to the coast start, then move without E
                    ext = max(0.0, d - (coast - remaining_after))
                    if ext > 1e-6:
                        m = P3[prev_i] + (q - P3[prev_i]) * (ext / d)
                        e += ext * e_per_mm * thick
                        out.append(f"G1 X{f(m[0])} Y{f(m[1])}{'' if planar else ' Z' + f(m[2])}{ax} E{e:.5f}")
                        st.volume_mm3 += ext * vol_per_mm * thick
                    out.append(f"G1 X{f(q[0])} Y{f(q[1])}{zs}{ax}")
                else:
                    e += d * e_per_mm * thick
                    out.append(f"G1 X{f(q[0])} Y{f(q[1])}{zs}{ax} E{e:.5f}")
                    st.volume_mm3 += d * vol_per_mm * thick
                if axes is not None:
                    st.max_tilt = max(st.max_tilt, math.degrees(math.acos(max(-1.0, min(1.0, float(axes[i][2]))))))
                if path.speeds is not None and i < len(path.speeds) and float(path.speeds[i]) < path.speed - 1.0 and path.kind in ("WALL-OUTER", "WALL-INNER", "SKIN"):
                    st.overhang_length += d
                st.extrusion_length += d
                dt = d / (feed_i / 60.0)
                st.time_s += dt
                st.by_type[path.kind] = st.by_type.get(path.kind, 0.0) + d
                st.by_type_time[path.kind] = st.by_type_time.get(path.kind, 0.0) + dt
                done += d
                prev_i = i
            cur = P3[idx[-1]] if idx else start
            # ---- wipe: move back along the loop while retracting
            if p.wipe_distance > 0 and p.retract_length > 0 and path.closed and path.kind in ("WALL-OUTER", "WALL-INNER") and not retracted:
                back = np.vstack([P3[idx[-1]], P3[idx[::-1][1:]]]) if len(idx) > 1 else None
                if back is not None:
                    left = p.wipe_distance
                    e -= p.retract_length
                    k = 0
                    while left > 1e-6 and k + 1 < len(back):
                        a, b = back[k], back[k + 1]
                        d = float(np.linalg.norm(b - a))
                        if d < 1e-9:
                            k += 1
                            continue
                        m = b if d <= left else a + (b - a) * (left / d)
                        out.append(f"G1 X{f(m[0])} Y{f(m[1])}{'' if planar else ' Z' + f(m[2])} E{e:.5f} F{feed:.0f}")
                        left -= min(d, left)
                        cur = m
                        k += 1
                    retracted = True
            if path.kind.startswith("SUPPORT"):
                st.support_volume += path.length * vol_per_mm
            all_pts.append(P3)
    st.e_total = e
    st.mass_g = st.volume_mm3 / 1000.0 * density
    if p.end_gcode.strip():
        out.extend(p.end_gcode.splitlines())
    out.append("M30")
    if all_pts:
        a = np.concatenate(all_pts)
        st.bounds = {"min": [float(a[:, 0].min()), float(a[:, 1].min()), float(a[:, 2].min())],
                     "max": [float(a[:, 0].max()), float(a[:, 1].max()), float(a[:, 2].max())]}
    return "\n".join(out) + "\n", st
