"""Write layer paths as G-code (Marlin/RepRap flavour, absolute XYZ, absolute E)."""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from .params import SliceParams
from .toolpath import Layer


@dataclass
class SliceStats:
    layers: int = 0
    paths: int = 0
    extrusion_length: float = 0.0  # mm of path with extrusion
    travel_length: float = 0.0
    e_total: float = 0.0  # E units (mm^3 or mm filament)
    time_s: float = 0.0
    dropped_chains: int = 0
    bounds: dict = field(default_factory=dict)
    by_type: dict = field(default_factory=dict)


def write_gcode(layers: list[Layer], params: SliceParams, source: str = "") -> tuple[str, SliceStats]:
    p = params
    st = SliceStats(layers=len(layers))
    out: list[str] = []
    f = lambda v: f"{v:.3f}"  # noqa: E731
    out.append(f"; generated by gcode2krl slicer" + (f" from {source}" if source else ""))
    out.append(f"; layer_height={p.layer_height} bead_width={p.bead_width} perimeters={p.perimeters} infill={p.infill_density} ({p.infill_pattern})")
    out.append("G21 ; mm")
    out.append("G90 ; absolute")
    out.append("M82 ; absolute E")
    out.append("G92 E0")
    if p.start_gcode.strip():
        out.extend(p.start_gcode.splitlines())
    e = 0.0
    cur = None  # current XY
    cur_z = None
    retracted = False
    all_pts = []
    for L in layers:
        if not L.paths:
            continue
        z = L.z + p.z_offset
        if p.comments:
            out.append(f";LAYER:{L.index}")
            out.append(f";Z:{z:.3f}")
        e_per_mm = p.extrusion_per_mm(p.bead_width, L.height)
        for path in L.paths:
            pts = path.points
            if len(pts) < 2:
                continue
            st.paths += 1
            if p.comments:
                out.append(f";TYPE:{path.kind}")
            start = pts[0]
            # ---- travel to the start
            dist = float(np.linalg.norm(start - cur)) if cur is not None else 0.0
            if cur is None or dist > 1e-6 or cur_z != z:
                if p.retract_length > 0 and dist >= p.min_travel_for_retract and not retracted:
                    e -= p.retract_length
                    out.append(f"G1 E{e:.5f} F{p.retract_speed:.0f}")
                    retracted = True
                hop = p.z_hop if (p.z_hop > 0 and dist >= p.min_travel_for_retract) else 0.0
                if hop > 0:
                    out.append(f"G0 Z{f(z + hop)} F{p.speed_travel:.0f}")
                if cur_z != z and hop == 0:
                    out.append(f"G0 Z{f(z)} F{p.speed_travel:.0f}")
                out.append(f"G0 X{f(start[0])} Y{f(start[1])} F{p.speed_travel:.0f}")
                if hop > 0:
                    out.append(f"G0 Z{f(z)} F{p.speed_travel:.0f}")
                cur_z = z
                st.travel_length += dist
                st.time_s += dist / (p.speed_travel / 60.0)
                if retracted:
                    e += p.retract_length
                    out.append(f"G1 E{e:.5f} F{p.retract_speed:.0f}")
                    retracted = False
            # ---- extrude along the path
            seq = list(pts) + ([pts[0]] if path.closed else [])
            feed = path.speed
            out.append(f"G1 F{feed:.0f}")
            prev = start
            for q in seq[1:]:
                d = float(np.linalg.norm(q - prev))
                if d < 1e-6:
                    continue
                e += d * e_per_mm
                out.append(f"G1 X{f(q[0])} Y{f(q[1])} E{e:.5f}")
                st.extrusion_length += d
                st.time_s += d / (feed / 60.0)
                st.by_type[path.kind] = st.by_type.get(path.kind, 0.0) + d
                prev = q
            cur = seq[-1]
            all_pts.append(pts)
    st.e_total = e
    if p.end_gcode.strip():
        out.extend(p.end_gcode.splitlines())
    out.append("M30")
    if all_pts:
        a = np.concatenate(all_pts)
        st.bounds = {"min": [float(a[:, 0].min()), float(a[:, 1].min()), float(layers[0].z + p.z_offset)],
                     "max": [float(a[:, 0].max()), float(a[:, 1].max()), float(layers[-1].z + p.z_offset)]}
    return "\n".join(out) + "\n", st
